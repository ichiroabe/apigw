<div class="card">
  <h2>システム ヘルプ</h2>
  <p>本システムのファイル・フォルダの権限や共有の仕組みについてご説明します。</p>

  <h3>基本的な見え方</h3>
  <p>本システムでは、基本的に「自分が作成したフォルダ・ファイル」と、「他の人から共有されているフォルダ・ファイル」だけが画面に表示されます。他のユーザーが非公開で作ったファイルは見えません。</p>

  <h3>フォルダについているマーク（バッジ）の意味</h3>
  <p>フォルダ名の横に付いているマークで、そのフォルダがどのような状態かを確認できます。</p>
  <ul>
    <li><span class="badge shared-view">🌐 共有(view)</span><br>
        全員が見ることと、ダウンロードすることだけができるフォルダです。ファイルの追加はできません。</li>
    <li><span class="badge shared">🌐 共有(edit)</span><br>
        全員がファイルを見たりダウンロードできるのに加え、新しくファイルをアップロード（追加）できるフォルダです。みんなでファイルを出し合う共同の場所として使われます。</li>
    <li><span class="badge" style="background-color:#666;color:#fff;">🔒 非共有</span><br>
        共有されているフォルダの中にありながら、特例として「他の人からは見えない（自分専用）」状態になっているフォルダです。</li>
  </ul>

  <h3>フォルダの共有設定（自分が作ったフォルダ）</h3>
  <p>自分が作成したフォルダの右側にある「操作」欄のプルダウンから、他の人への見せ方を変更することができます。</p>
  <ul>
    <li><strong>継承(未設定)</strong>：親フォルダと同じ設定になります。親が共有されていれば共有され、親が非公開なら非公開になります。</li>
    <li><strong>非共有(遮断)</strong>：親フォルダが全員に共有されていても、このフォルダだけは他の人から見えない「自分だけの秘密のフォルダ」になります。</li>
    <li><strong>共有(view) / 共有(edit)</strong>：親フォルダの状態にかかわらず、このフォルダの中身を全員に公開します（閲覧のみ、または追加も許可）。</li>
  </ul>

  <h3>【重要】ファイルの削除に関するルール</h3>
  <p>システム上の重要なデータが誤って消去されるのを防ぐため、削除に関しては以下のルールが適用されています。</p>
  <ul>
    <li>「自分がアップロードしたファイル（または作成したフォルダ）」しか削除できません。</li>
    <li><code>共有(edit)</code> のフォルダ内であっても、他人がアップロードしたファイルは削除できません。もし間違ったファイルがアップロードされている場合は、アップロードしたご本人、またはシステムの管理者へ削除をご依頼ください。</li>
  </ul>

  <h3>権限と個別アクセス権（グループ）の優先順位</h3>
  <p>1つのフォルダに対して、プルダウンでの共有設定（全員対象）と、個別アクセス権（特定のグループ対象）の両方が設定されている場合、システムは<strong>「その人にとって一番強い（有利な）権限」</strong>を優先して適用します。</p>
  <ul>
    <li><strong>全体は「共有(view)」だが、特定グループには「edit」の場合：</strong><br>
        グループの人は「追加・整理(改名/移動)が可能」、それ以外の人は「閲覧のみ(view)」となります。<em>（推奨される安全な使い方です）</em></li>
    <li><strong>全体は「共有(edit)」だが、特定グループには「view」の場合：</strong><br>
        すでに全員に強い権限(edit)を開放しているため、全員が「追加・整理(改名/移動)が可能」のままとなります。</li>
    <li><strong>特例：すべてを無効化する「非共有(遮断)」</strong><br>
        親フォルダからどれだけ強い権限が与えられていても、フォルダを「非共有(遮断)」にすると、全員の権限もグループの権限もすべてブロックされ、他人からは見えなくなります。</li>
  </ul>
</div>

